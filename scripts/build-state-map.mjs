// Rebuild: download https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/states-albers-10m.json
// then run node scripts/build-state-map.mjs /path/to/states-albers-10m.json
import {readFileSync,writeFileSync} from 'node:fs';
import {STATES} from '../dist/race-data.mjs';
const topology=JSON.parse(readFileSync(process.argv[2],'utf8'));
const {scale,translate}=topology.transform;
const arcs=topology.arcs.map(arc=>{let x=0,y=0;return arc.map(p=>{x+=p[0];y+=p[1];return [x*scale[0]+translate[0],y*scale[1]+translate[1]];});});
function ring(ids) {return ids.flatMap((id,i)=>{const pts=id<0?[...arcs[~id]].reverse():arcs[id];return i?pts.slice(1):pts;});}
function centroid(points) {let twiceArea=0,x=0,y=0;for(let i=0;i<points.length-1;i++){const a=points[i],b=points[i+1],cross=a[0]*b[1]-b[0]*a[1];twiceArea+=cross;x+=(a[0]+b[0])*cross;y+=(a[1]+b[1])*cross;}return {area:Math.abs(twiceArea),x:x/(3*twiceArea),y:y/(3*twiceArea)};}
const shapes={};
for(const s of STATES){
 const g=topology.objects.states.geometries.find(g=>g.properties.name===s.name);
 if(!g)throw new Error(`Missing state: ${s.name}`);
 const polygons=g.type==='Polygon'?[g.arcs]:g.arcs;
 const rings=polygons.flatMap(p=>p.map(ring));
 const center=polygons.map(p=>centroid(ring(p[0]))).sort((a,b)=>b.area-a.area)[0];
 shapes[s.code]={d:rings.map(r=>'M'+r.map(p=>p.map(n=>n.toFixed(1)).join(',')).join('L')+'Z').join(''),x:+center.x.toFixed(1),y:+center.y.toFixed(1)};
}
// Label positions adjusted for archipelagos and irregular state outlines.
Object.assign(shapes.HI,{x:275,y:558});Object.assign(shapes.MI,{x:700,y:185});Object.assign(shapes.FL,{x:805,y:530});
writeFileSync(new URL('../dist/state-shapes.mjs',import.meta.url),'// Census 2017 state boundaries via us-atlas 3.0.1 (ISC). See us-atlas-LICENSE.txt.\n// Albers USA projection; Alaska and Hawaii are inset. Generated by scripts/build-state-map.mjs.\nexport const STATE_SHAPES = '+JSON.stringify(shapes)+';\n');
console.log(`Generated ${Object.keys(shapes).length} geographic state paths.`);
